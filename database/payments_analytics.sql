-- Member 4: Payments & Analytics (discounts, payments, overdue, reporting).
-- Run in the Supabase SQL Editor AFTER schema.sql and AFTER the products/plans
-- (Member 2) and subscriptions/invoices (Member 3) tables exist.
-- For local development without those tables, run dev/member3_tables_stub.sql first.
--
-- Reads (see README "Payments & analytics"): profiles, products, plans,
-- subscriptions, subscription_items, invoices. Owns: discounts, discount_targets,
-- discount_usages, payments. Ids of teammates' tables are assumed to be uuid.

create table if not exists public.discounts (
  id            bigint generated by default as identity primary key,
  name          text not null,
  code          text unique,
  type          text not null check (type in ('FIXED','PERCENT')),
  value         numeric(12,2) not null check (value > 0),
  scope         text not null check (scope in ('PRODUCT','SUBSCRIPTION')),
  min_purchase  numeric(12,2) not null default 0 check (min_purchase >= 0),
  min_quantity  int not null default 0 check (min_quantity >= 0),
  start_date    date not null,
  end_date      date,
  usage_limit   int check (usage_limit is null or usage_limit >= 1),
  used_count    int not null default 0 check (used_count >= 0),
  is_active     boolean not null default true,
  created_by    uuid references public.profiles(id),
  created_at    timestamptz not null default now(),
  check (type <> 'PERCENT' or value <= 100),
  check (end_date is null or end_date >= start_date),
  check (usage_limit is null or used_count <= usage_limit)
);
create index if not exists discounts_live_idx on public.discounts (is_active, start_date, end_date);

-- What a discount targets. No rows = applies to everything in its scope.
-- target_type PRODUCT -> products.id, SUBSCRIPTION -> subscriptions.id
create table if not exists public.discount_targets (
  discount_id  bigint not null references public.discounts(id) on delete cascade,
  target_type  text not null check (target_type in ('PRODUCT','SUBSCRIPTION')),
  target_id    uuid not null,
  primary key (discount_id, target_type, target_id)
);

-- One row per (discount, invoice). The primary key makes usage counting idempotent.
create table if not exists public.discount_usages (
  discount_id  bigint not null references public.discounts(id),
  invoice_id   uuid not null references public.invoices(id),
  amount       numeric(12,2) not null check (amount >= 0),
  created_at   timestamptz not null default now(),
  primary key (discount_id, invoice_id)
);
create index if not exists discount_usages_invoice_idx on public.discount_usages (invoice_id);

create table if not exists public.payments (
  id               bigint generated by default as identity primary key,
  invoice_id       uuid not null references public.invoices(id),
  customer_id      uuid not null references public.profiles(id),  -- denormalised for fast history queries
  method           text not null check (method in ('CASH','BANK_TRANSFER','CARD','UPI','CHEQUE','OTHER')),
  amount           numeric(12,2) not null check (amount > 0),
  payment_date     date not null,
  note             text,
  reference        text,
  status           text not null default 'POSTED' check (status in ('POSTED','VOIDED')),
  idempotency_key  text unique,
  recorded_by      uuid references public.profiles(id),
  void_reason      text,
  voided_by        uuid references public.profiles(id),
  voided_at        timestamptz,
  created_at       timestamptz not null default now()
);
create index if not exists payments_invoice_posted_idx on public.payments (invoice_id) include (amount) where status = 'POSTED';
create index if not exists payments_customer_date_idx  on public.payments (customer_id, payment_date);
create index if not exists payments_date_idx           on public.payments (payment_date) include (amount, method) where status = 'POSTED';

-- Indexes this module needs on teammates' tables (harmless if they already exist).
create index if not exists invoices_status_due_idx    on public.invoices (status, due_date);
create index if not exists invoices_customer_idx      on public.invoices (customer_id);
create index if not exists invoices_invoice_date_idx  on public.invoices (invoice_date);
create index if not exists invoices_subscription_idx  on public.invoices (subscription_id);
create index if not exists subscriptions_status_idx   on public.subscriptions (status);
create index if not exists subscriptions_plan_idx     on public.subscriptions (plan_id);
create index if not exists subscription_items_sub_idx on public.subscription_items (subscription_id);

-- All reads and writes go through the Express API (server-side Postgres
-- connection). RLS on with no policies: the anon/authenticated keys can't
-- touch these tables directly through the Supabase client.
alter table public.discounts        enable row level security;
alter table public.discount_targets enable row level security;
alter table public.discount_usages  enable row level security;
alter table public.payments         enable row level security;
revoke all on public.discounts, public.discount_targets, public.discount_usages, public.payments from anon, authenticated;
