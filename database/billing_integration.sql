-- Joins the team's tables into one working schema.
-- Run in the Supabase SQL Editor, in this order:
--   schema.sql, product_catalog.sql, subscriptions_billing.sql,
--   billing_integration.sql, payments_analytics.sql

-- Links Member 3's tables to the real customers, plans and products.
alter table public.subscriptions
  add constraint subscriptions_customer_fk foreign key (customer_id) references public.profiles(id),
  add constraint subscriptions_plan_fk foreign key (plan_id) references public.plans(id);
alter table public.subscription_items
  add constraint subscription_items_product_fk foreign key (product_id) references public.products(id),
  add constraint subscription_items_variant_fk foreign key (product_variant_id) references public.product_variants(id);
alter table public.invoices
  add constraint invoices_customer_fk foreign key (customer_id) references public.profiles(id);
alter table public.invoice_items
  add constraint invoice_items_product_fk foreign key (product_id) references public.products(id);

-- Fields the brief needs that the first version of the tables did not have.
alter table public.subscriptions
  add column if not exists payment_terms_days integer not null default 15 check (payment_terms_days >= 0),
  add column if not exists quote_expires_on date,
  add column if not exists renewed_from uuid references public.subscriptions(id);
alter table public.invoices
  alter column subscription_id drop not null,
  add column if not exists sent_at timestamptz;
alter table public.quotation_templates
  add column if not exists plan_id uuid references public.plans(id);

-- Team-visible history of every subscription.
create table if not exists public.subscription_events (
  id bigint generated by default as identity primary key,
  subscription_id uuid not null references public.subscriptions(id) on delete cascade,
  from_status text,
  to_status text not null,
  note text,
  actor_id uuid references public.profiles(id),
  created_at timestamptz not null default now()
);
create index if not exists subscription_events_sub_idx on public.subscription_events (subscription_id, created_at);

-- Readable numbers: SUB/2026/0001 and INV/2026/0001. A row per series and year.
create table if not exists public.number_series (
  series text not null,
  year integer not null,
  last_value integer not null default 0,
  primary key (series, year)
);

-- All access goes through the Express API. RLS with no policies keeps the
-- public Supabase keys away from these tables.
do $$ declare t text; begin
  foreach t in array array['subscriptions','subscription_items','tax_rules','invoices','invoice_items','subscription_events','number_series'] loop
    execute format('alter table public.%I enable row level security', t);
    execute format('revoke all on public.%I from anon, authenticated', t);
  end loop;
end $$;
